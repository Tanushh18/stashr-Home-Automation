/*
  Loads Stashr's own .glb models (client/public/models, generated by scripts/build-models.mjs).
  GLTFLoader is imported on demand so it lives in the lazy 3D chunk. Callers keep their
  code-built geometry until a model arrives, so a failed load changes nothing visible.
*/
const base = () => {
  try { return import.meta.env?.BASE_URL || "/"; } catch { return "/"; }
};

export const MODEL_URLS = {
  shield: "models/stashr-shield.glb",
  vaultDoor: "models/vault-door.glb",
};

export async function loadModel(name) {
  const { GLTFLoader } = await import("three/examples/jsm/loaders/GLTFLoader.js");
  const gltf = await new GLTFLoader().loadAsync(base() + MODEL_URLS[name]);
  return gltf.scene;
}

/** Frees a subtree's GPU resources (used when a model arrives after its scene was closed). */
export function disposeTree(obj) {
  obj.traverse((o) => {
    o.geometry?.dispose?.();
    const m = o.material;
    (Array.isArray(m) ? m : m ? [m] : []).forEach((x) => x.dispose());
  });
}
